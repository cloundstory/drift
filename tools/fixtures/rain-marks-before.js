function rainMarks(L,tf){
  const f=rainOf(L);
  if(!f) return null;
  const bucket=Math.round(clamp(tf||0,0,1)*6);
  const key=L.id+':'+bucket;
  if(_rainMarks.has(key)) return _rainMarks.get(key);
  const wind=wfOf(L);
  const pts=f.pts, half=pts.half, N=34, out=[];
  const hs=(n)=>{ const x=Math.sin(n*12.9898)*43758.5453; return x-Math.floor(x); };
  /* ---------- กรอบท้องถิ่นของเส้นทาง ----------
     al = ตามแนวเส้นทาง · cr = ตามแนวขวาง · ใช้ร่วมกันทั้งเมฆ ฝน และก้อนฟ้าคะนอง */
  const llAt=(al,cr)=>{
    const mid=pts.mid;
    let q = al===0 ? {lat:mid.lat,lng:mid.lng}
                   : destPoint(mid.lat,mid.lng, al>0?pts.brg:(pts.brg+180)%360, Math.abs(al));
    if(cr!==0) q=destPoint(q.lat,q.lng,(pts.brg+90)%360,cr);
    return q;
  };
  /* ---------- โครงสร้างขอบเมฆ (ข้อ 84.10) ----------
     ⚠️ ข้อมูลฝนของเราเป็นตาราง 8×8 ทั้งสนาม = ช่องกว้าง 1,714 กม. บนเส้นทางไกล
     พอไล่สีเรียบ ๆ ระหว่างช่อง เราจึงได้ *รอยเปื้อนนุ่ม ๆ* ที่ไม่มีขอบ
     **ต่อให้ถมจนดำแค่ไหนก็ไม่มีวันอ่านเป็นเมฆ เพราะเมฆถูกจำด้วยรูปทรง ไม่ใช่ด้วยความดำ**

     แก้ด้วยการเอา noise หลายความถี่มาคูณกับปริมาณฝน *เฉพาะตอนวาด*
     ตรงที่ฝนเป็นศูนย์ยังเป็นศูนย์ (คูณแล้วก็ยังศูนย์) แต่ตรงขอบ ๆ จะแตกเป็นหยัก
     **มวลและตำแหน่งยังมาจากข้อมูลจริงทุกกระเบียด — noise สร้างแค่รายละเอียดที่ข้อมูลไม่มีความละเอียดพอจะบอก**
     และเป็น hash ล้วน ไม่ใช่ Math.random ผู้ส่งกับผู้รับจึงเห็นก้อนเมฆรูปเดียวกันเป๊ะ */
  const NZ=128, nz=new Float32Array(NZ*NZ);
  {
    const vn=(x,y)=>{
      const xi=Math.floor(x), yi=Math.floor(y), xf=x-xi, yf=y-yi;
      const u=xf*xf*(3-2*xf), v=yf*yf*(3-2*yf);
      const g=(px,py)=>hs(px*157.31+py*311.7+13.1);
      return g(xi,yi)*(1-u)*(1-v)+g(xi+1,yi)*u*(1-v)+g(xi,yi+1)*(1-u)*v+g(xi+1,yi+1)*u*v;
    };
    for(let r=0;r<NZ;r++) for(let c=0;c<NZ;c++){
      const x=r/NZ, y=c/NZ;
      nz[r*NZ+c]=vn(x*3,y*3)*0.55+vn(x*7.3+11,y*7.3+5)*0.30+vn(x*17.1+23,y*17.1+29)*0.15;
    }
  }
  const nzAt=(al,cr)=>{
    const x=clamp((al/half+1)/2,0,0.9999)*(NZ-1), y=clamp((cr/half+1)/2,0,0.9999)*(NZ-1);
    const xi=Math.floor(x), yi=Math.floor(y), xf=x-xi, yf=y-yi;
    const i0=xi*NZ+yi, i1=Math.min(NZ-1,xi+1)*NZ+yi, j=Math.min(NZ-1,yi+1)-yi;
    return (nz[i0]*(1-xf)+nz[i1]*xf)*(1-yf)+(nz[i0+j]*(1-xf)+nz[i1+j]*xf)*yf;
  };
  /* ---------- ก้อนฟ้าคะนอง (ข้อ 85) ----------
     กอล์ฟ 25 ส.ค.: "เมฆก้อนไหนที่เป็นฝนฟ้าคะนองก็ต้องมีฟ้าแลบ"

     ฟ้าแลบวางตามจุดบนเส้นทางที่ `weather_code` บอกว่าฟ้าคะนองจริง (95-99)
     แต่สนามฝนตรงนั้นอาจบางมาก แสงวาบจึงเคยลอยอยู่บนฟ้าโล่ง

     WMO 95-99 แปลว่ามีเมฆก่อตัวสูง ซึ่ง *หนากว่า* ที่สนามฝนหยาบ ๆ บอกได้อยู่แล้ว
     จึงเพิ่มมวลเมฆเฉพาะรอบจุดฟ้าคะนอง — เป็นความจริงทางอุตุฯ ไม่ใช่การตกแต่ง
     ผลคือฟ้าแลบมีก้อนเมฆให้อยู่เสมอ และก้อนนั้นเป็นก้อนที่เข้มที่สุดในภาพ */
  /* ---------- จุดอากาศหนักบนเส้นทาง (ข้อ 85, 88) ----------
     `weather_code` มีแค่ 13 จุดบนเส้นทาง แต่มันบอกสิ่งที่สนามฝนหยาบ ๆ บอกไม่ได้
     WMO 95-99 = เมฆก่อตัวสูง · 71-77 = หิมะ · 56/57/66/67 = ฝนแข็งตัว
     ทั้งสามอย่างตกลงมาจากเมฆทั้งนั้น ถ้าไม่เพิ่มมวลให้ มันจะร่วงออกมาจากฟ้าโล่ง */
  const WX=[];
  if(L.lg) for(let i=0;i<L.lg.length;i++){
    const wc=L.lg[i][8]||0;
    let kind=0, mass=0;
    const x=wcx(wc);                    /* 1 หิมะ · 2 ฝนแข็งตัว · 3 หมอก — ตัวเดียวกับที่คำเรียกใช้ */
    if(wc>=95)      { kind=1; mass=2.4; }   /* ฟ้าคะนอง */
    else if(x===1)  { kind=2; mass=1.5; }   /* หิมะ — เมฆเรียบ ไม่มีแกนหนัก */
    else if(x===2)  { kind=3; mass=1.9; }   /* ฝนแข็งตัว */
    else if(x===3)  { kind=4; mass=0; }     /* หมอก — ไม่มีมวลเมฆ */
    if(!kind) continue;
    const q=fromXYZ(posVAt(L,(i+0.5)/L.lg.length));
    /* แปลงเป็นพิกัดในกรอบเส้นทางครั้งเดียว แล้ววัดระยะในกรอบนั้นตรง ๆ
       ถูกกว่าการทำตารางแล้ว gcDist ทุกช่องมาก และแม่นพอสำหรับก้อนกลม ๆ */
    const d=gcDist(pts.mid,q), b=(bearing(pts.mid,q)-pts.brg)*RAD;
    WX.push({kind, mass, lat:q.lat, lng:q.lng, al:d*Math.cos(b), cr:d*Math.sin(b)});
  }
  const sRad2=(half*0.17)*(half*0.17);
  const sbAt=(al,cr)=>{
    let s=0;
    for(const w of WX){
      if(!w.mass) continue;
      const dx=al-w.al, dy=cr-w.cr;
      const e=Math.exp(-(dx*dx+dy*dy)/sRad2)*(w.mass/2.4);
      if(e>s) s=e;
    }
    return s;
  };
  /* ปริมาณฝนที่ใช้ *วาด* — ของจริง × โครงสร้างขอบ + มวลของเมฆฟ้าคะนอง */
  const mmDraw=(al,cr,q)=>rainAt(f,q.lat,q.lng,bucket/6)*(0.35+1.35*nzAt(al,cr))+2.4*sbAt(al,cr);

  /* รัศมีของก้อนอากาศหนัก — ใช้ร่วมกันระหว่างการวางหิมะ/น้ำแข็ง/หมอก
     และการห้ามเม็ดฝนร่วงในก้อนเดียวกัน สองที่นี้ต้องเป็นค่าเดียวกันเสมอ */
  const wxR=half*0.20;
  /* ---------- ในก้อนหิมะหรือฝนแข็งตัว ห้ามมีเม็ดฝนร่วง (ข้อ 88.1) ----------
     ข้อ 88 เพิ่มมวลเมฆให้หิมะกับฝนแข็งตัว เพื่อไม่ให้มันร่วงออกมาจากฟ้าโล่ง — ถูกแล้ว
     แต่ `mmDraw` เอามวลก้อนนั้นไปเลี้ยง *เม็ดฝน* ด้วย เพราะ fall รู้จักแต่ปริมาณน้ำฟ้า
     วัดแล้ว: ใส่หิมะหนึ่งช่วงทำให้เม็ดฝนเพิ่มจาก 276 เป็น 413 เส้น (+137)
     ฝนแข็งตัว +158 · หมอกไม่เพิ่มเลยเพราะมวลเป็นศูนย์อยู่แล้ว

     ผลที่ตาเห็นคือจุดขาวส่ายช้ากับขีดฝนเอียงตามลม *ร่วงทับกัน* ในก้อนเดียว
     ซึ่งขัดกฎแกนของงานภาพชุดนี้: แต่ละอย่างต้องใช้ช่องทางการมองเห็นคนละช่อง
     ตัดเฉพาะของที่ร่วง ไม่แตะมวลเมฆ — เมฆที่หิมะตกลงมาจากต้องมีอยู่ต่อไป */
  const solidR2=wxR*wxR;
  const inSolid=(al,cr)=>{
    for(const w of WX){
      if(w.kind!==2&&w.kind!==3) continue;   /* 2 หิมะ · 3 ฝนแข็งตัว */
      const dx=al-w.al, dy=cr-w.cr;
      if(dx*dx+dy*dy<solidR2) return true;
    }
    return false;
  };

  /* ---------- ฝนที่ตกลงมาจากเมฆ (ข้อ 85) ----------
     ข้อ 67 เคยวาดขีดฝนทั่วสนามแล้วข้อ 70 ลบทิ้ง เพราะ *ไม่มีเมฆให้มันตกลงมาจาก*
     กอล์ฟพูดเองตอนนั้นว่า "ถ้าเราไม่เขียนระบุ น้อยคนมากจะเห็นว่าเส้นพวกนี้คือฝน"

     ตอนนี้มีเมฆแล้ว ขีดชุดเดียวกันจึงอ่านต่างไปคนละเรื่อง — แต่ต้องต่างจากของเดิมสองข้อ:
     **หนึ่ง วาดเฉพาะแกนที่หนักที่สุด** ไม่ใช่ทั่วสนาม ฝนจึงเป็นสิ่งที่ *ก้อนหนึ่ง* ทำ ไม่ใช่บรรยากาศทั่วไป
     **สอง เอียงตามลมจริง** ต่างจากลายเมฆที่มุมคงที่ ตาจึงแยกออกว่าอันไหนคือเนื้อเมฆ อันไหนคือของที่ร่วงลงมา */
  /* ---------- ฝนคือสิ่งเดียวที่ *ร่วง* (ข้อ 86) ----------
     ข้อ 85 ลองวาดฝนเป็นขีดนิ่ง ๆ สี่แบบ ไม่ผ่านสักแบบ เพราะเมฆกินช่องทางไปหมดแล้ว —
     ทั้งคู่เป็นขีดดินสอสั้น สีเดียวกัน บนทรงกลมเดียวกัน

     ช่องทางที่ยังว่างคือ **การเคลื่อนไหว** และต้องเป็นการเคลื่อนไหวคนละชนิดกับลมด้วย:
       ริ้วลม = *คลื่นสว่าง* วิ่งไปบนเส้นที่อยู่กับที่ (เส้นไม่ขยับ)
       ฝน     = *ตัวขีดเอง* เคลื่อนที่ แล้วหายไป แล้วมีตัวใหม่โผล่มาแทน

     และฝนวิ่งเป็น *เส้นตรง* ต่างจากลมที่คดไปตามสนาม — ฝนตกเป็นลำ ไม่ได้เลื้อย

     เก็บเป็นรางไว้ล่วงหน้า (จุดบนทรงกลม 8 จุดต่อราง) ตอนวาดแค่เลือกช่วงตามเฟส
     จึงไม่ต้องคำนวณพิกัดใหม่ทุกเฟรม — เฟรมหนึ่งเสียแค่ rotate+project 2 จุดต่อราง */
  const RN=96, CORE=0.62, rcell=half*2/RN, RK=8, fall=[];
  for(let r=0;r<RN;r++) for(let c=0;c<RN;c++){
    const al0=((r+0.5)/RN-0.5)*2*half;
    const cr0=((c+0.5+(r%2)*0.5)/RN-0.5)*2*half;
    const p0=llAt(al0,cr0);
    const mm=mmDraw(al0,cr0,p0);
    if(mm<CORE) continue;                       /* ฝนออกจาก *แกน* ของระบบเท่านั้น */
    /* เช็กหลังเกณฑ์แกน ไม่ใช่ก่อน — จุดส่วนใหญ่ถูกตัดด้วย CORE ไปแล้ว
       วนลูป WX ให้เฉพาะจุดที่รอดมาถึงตรงนี้จึงถูกกว่ามาก */
    if(inSolid(al0,cr0)) continue;              /* ในก้อนหิมะ/ฝนแข็งตัว ห้ามมีฝน */
    const d=Math.min(1,(mm-CORE)/1.3);
    const n=r*97+c*31;
    if(hs(n)>0.30+0.55*d) continue;
    let brg=pts.brg+90;
    if(wind){ const w=wfAt(wind,p0.lat,p0.lng,bucket/6); if(Math.hypot(w.e,w.n)>0.5) brg=Math.atan2(w.e,w.n)*DEG; }
    /* เยื้องจุดตั้งต้นเล็กน้อย ไม่งั้นรางจะเรียงเป็นตาราง */
    let q=destPoint(p0.lat,p0.lng,(brg+90)%360,(hs(n*3.3)-0.5)*rcell*0.9);
    const step=rcell*(0.55+0.30*hs(n*7.7));
    const track=[];
    for(let k=0;k<=RK;k++){
      track.push(toXYZ(q.lat,q.lng));
      q=destPoint(q.lat,q.lng,brg,step);
    }
    /* ช้าลงราวหนึ่งในสาม — กอล์ฟ 25 ส.ค.: "อยากให้มันนิ่มกว่านี้หน่อย" */
    fall.push({p:track, sp:0.28+0.22*hs(n*9.1), ph:hs(n*11.3), w:0.5+0.5*d});
  }
  out.fall=fall;

  /* ---------- หิมะ · หมอกจริง · ฝนแข็งตัว (ข้อ 88) ----------
     สามอันนี้ขับด้วย `weather_code` ที่เก็บอยู่แล้ว ไม่ต้องขอข้อมูลเพิ่มสักช่อง
     แต่ละอันต้องใช้ *ช่องทางการมองเห็นคนละช่อง* กับเมฆ ลม และฝน (ข้อ 85.3)
       หิมะ    = จุดสว่างที่ *ยกกระดาษ* ไม่ใช่รอยที่ลงบนกระดาษ · ส่ายไปมา · ช้ามาก
       หมอก    = ยางลบ ไม่ใช่สีที่ทาทับ · ไม่เคลื่อน หายใจช้า ๆ
       ฝนแข็งตัว = ร่วงตรงสนิท เร็วกว่าฝน + ประกายที่หัว + รอยแตกที่ค้างอยู่ */
  const snow=[], fogp=[], ice=[], crack=[];   /* wxR ประกาศไว้ข้างบนแล้ว ใช้ร่วมกับ inSolid */
  for(let wi=0;wi<WX.length;wi++){
    const w=WX[wi];
    if(w.kind===2){
      for(let k=0;k<240;k++){
        const n=wi*991+k*17.3;
        const q0=destPoint(w.lat,w.lng,hs(n)*360,Math.sqrt(hs(n*3.1))*wxR);
        const brg=hs(n*7.7)*360, track=[];
        let q={lat:q0.lat,lng:q0.lng};
        for(let m=0;m<=6;m++){
          track.push(toXYZ(q.lat,q.lng));
          /* ส่ายไปมา — นี่คือสิ่งที่บอกว่าเป็นหิมะ ไม่ใช่ฝน */
          q=destPoint(q.lat,q.lng,(brg+Math.sin(m*1.15+hs(n*5.3)*6.283)*34+360)%360, wxR*0.075);
        }
        snow.push({p:track, sp:0.10+0.07*hs(n*11.1), ph:hs(n*13.7), w:0.5+0.5*hs(n*19.3)});
      }
    } else if(w.kind===3){
      for(let k=0;k<140;k++){
        const n=wi*733+k*29.7;
        const q0=destPoint(w.lat,w.lng,hs(n)*360,Math.sqrt(hs(n*3.3))*wxR);
        const brg=hs(n*7.1)*360, track=[];
        let q={lat:q0.lat,lng:q0.lng};
        for(let m=0;m<=6;m++){ track.push(toXYZ(q.lat,q.lng));
          q=destPoint(q.lat,q.lng,brg,wxR*0.085); }        /* ไม่ส่ายเลย */
        ice.push({p:track, sp:0.42+0.26*hs(n*11.7), ph:hs(n*13.1), w:0.5+0.5*hs(n*17.9)});
      }
      for(let k=0;k<40;k++){
        const n=wi*311+k*41.3;
        const q0=destPoint(w.lat,w.lng,hs(n)*360,Math.sqrt(hs(n*5.1))*wxR*0.95);
        crack.push({a:toXYZ(q0.lat,q0.lng), s:0.55+0.55*hs(n*3.9), ph:hs(n*7.7)*6.283});
      }
    } else if(w.kind===4){
      for(let k=0;k<52;k++){
        const n=wi*577+k*23.1;
        const q0=destPoint(w.lat,w.lng,hs(n)*360,Math.sqrt(hs(n*3.7))*wxR*1.15);
        fogp.push({a:toXYZ(q0.lat,q0.lng), r:wxR*(0.24+0.20*hs(n*5.9)),
                   ph:hs(n*9.3)*6.283, w:0.45+0.55*hs(n*7.1)});
      }
    }
  }
  out.snow=snow; out.fogp=fogp; out.ice=ice; out.crack=crack;

  const HN=340, HS=46, hatch=[];
  const HR=half*1.45, dU=2*HR/HS;
  const layer=(angDeg,minMM,gain,base,offFrac,seed)=>{
    const ang0=angDeg*RAD;
    for(let i=0;i<HN;i++){
      const off=((i+0.5+offFrac)/HN-0.5)*2*HR;
      for(let k=0;k<HS;k++){
        const n=i*131.7+k*7.3+seed;
        /* มือคนไม่ได้ลากเป็นตาราง — เอียงไม่เท่ากันนิดหน่อยและยาวไม่เท่ากัน
           ถ้าไม่มีตรงนี้ มันอ่านเป็น *ลายที่ถูกปั๊ม* ไม่ใช่รอยที่ถูกถม */
        /* ส่ายน้อยลงมาก — ถ้าส่ายเยอะตอนเส้นถี่ มันจะกลายเป็นขยุกขยิก ไม่ใช่พื้นที่ถูกถม */
        const ang=ang0+(hs(n*1.7)-0.5)*0.06;
        const ca=Math.cos(ang), sa=Math.sin(ang);
        const u0=((k+0.5)/HS-0.5)*2*HR;
        const al0=u0*ca-off*sa, cr0=u0*sa+off*ca;
        if(Math.abs(al0)>half||Math.abs(cr0)>half) continue;
        const q0=llAt(al0,cr0);
        const mm=mmDraw(al0,cr0,q0);
        if(mm<minMM) continue;
        /* ⚠️ ยกพื้นด้วย base — ตรงไหนมีเมฆพอจะเห็น ต้องได้เส้นชุดที่ *ต่อเนื่องกัน*
           ถ้าปล่อยให้ค่าน้อย ๆ ได้ความถี่น้อย ๆ ตามสัดส่วน มันจะอ่านเป็นขีดกระจัดกระจาย
           ไม่ใช่เนื้อที่ถูกถม — ความต่างต้องชัดระหว่าง "มีเมฆ" กับ "ไม่มี" ก่อน
           แล้วค่อยไล่ระดับภายในส่วนที่มี */
        const d=base+(1-base)*Math.min(1,Math.pow((mm-minMM)/gain,0.7));
        if(hs(n)>d) continue;
        /* ⚠️ ยาวกว่าระยะก้าว — ขีดที่ผ่านเกณฑ์ติดกันจึง *ต่อกันเป็นเส้นยาว* เอง
           ตรงไหนถี่จะได้เส้นยาวต่อเนื่อง ตรงไหนบางจะเหลือเป็นขีดสั้น
           ซึ่งคือหน้าตาของการแรเงาด้วยมือจริง ๆ ถ้าสั้นกว่าก้าวเสมอ จะได้แต่ขีดกระจาย */
        const u1=u0+dU*(1.5+hs(n*3.1)*0.8);
        const q1=llAt(u1*ca-off*sa, u1*sa+off*ca);
        hatch.push({a:toXYZ(q0.lat,q0.lng), b:toXYZ(q1.lat,q1.lng), w:0.5+0.5*d});
      }
    }
  };
  /* ค่าพวกนี้ปรับจาก *การกระจายจริงของฝน* ไม่ได้เดา — วัดสนามหนึ่งได้
     ค่ากลาง 0.07 · p90 0.28 · p97 0.50 · สูงสุด 1.88 มม. และมีฝน 62% ของพื้นที่
     ชุดแรกที่ตั้งไว้ (gain 2.2) ให้เส้นแค่ 137 เส้นทั้งสนาม = แทบมองไม่เห็น */
  /* ⚠️ เกณฑ์ต่ำสุดคือตัวกำหนด *รูปร่าง* ของเมฆ
     ตั้งไว้ 0.05 (ต่ำกว่าค่ากลาง 0.07) ทำให้ 62% ของสนามมีเส้นหมด = ไม่มีขอบให้อ่าน
     0.10 อยู่ราวเปอร์เซ็นไทล์ที่ 60 ของการกระจายจริง เหลือพื้นที่มีเมฆราว 40%
     ฟ้าโปร่งจึงกลับมาเป็นฟ้าโปร่งจริง ๆ และก้อนเมฆมีรูปทรง */
  /* ⚠️ ชั้นแรก base 0.85 ไม่ใช่ 0.60 — ตรงไหนนับว่ามีเมฆ ต้องถูกถม *เกือบเต็ม* ที่ระยะห่างพื้นฐาน
     ที่ 0.60 มันข้ามตำแหน่งไป 40% ซึ่งเป็นเหตุผลที่ยังดูโปร่งแม้เส้นจะชิดขึ้นแล้ว
     ความมืดที่เพิ่มขึ้นตามปริมาณฝน มาจากชั้น 2-6 ที่ซ้อนทับ ไม่ใช่จากการเติมช่องว่างของชั้นแรก */
  layer(-28, 0.10, 0.55, 0.85, 0.00,   0);     /* ชั้น 1 — ถมทั่วบริเวณที่มีเมฆ */
  layer(-28, 0.22, 0.60, 0.45, 0.50, 991);     /* ชั้น 2 — แทรกกลางเส้นเดิม ตรงที่หนักขึ้น */
  layer(-13, 0.30, 0.70, 0.40, 0.25, 557);     /* ชั้น 3 — เอียงต่างนิดหน่อย */
  layer( 46, 0.55, 0.80, 0.35, 0.00, 313);     /* ชั้น 4 — ตัดขวาง เฉพาะแกนที่หนักจริง */
  /* ⚠️ เพดานความมืด = *จำนวนชั้น* ไม่ใช่ค่า alpha
     สี่ชั้นแรกตันที่ราวสี่รอยต่อช่อง ซึ่งพอสำหรับฝนระดับที่วัดเจอในสนามนี้ (สูงสุด 1.88 มม.)
     แต่ฝนเขตร้อนจริงไปได้ถึงหลักสิบ มม./ชม. — ถ้าไม่มีชั้นต่อ มันจะตันแล้วดูเท่าฝนปานกลาง
     สองชั้นนี้จึงไม่ทำงานเลยกับข้อมูลชุดที่ทดสอบ [ยังไม่ได้ยืนยันกับฝนหนักจริง] */
  layer(-28, 1.20, 1.50, 0.50, 0.25, 137);     /* ชั้น 5 — ฝนหนัก */
  layer( 13, 2.50, 2.50, 0.50, 0.75, 701);     /* ชั้น 6 — ฝนหนักมาก */
  out.hatch=hatch;
  cachePut(_rainMarks,key,out,40);
  return out;
}

