function renderGlobe(dt=1/60){
  sctx.clearRect(0,0,W,H);
  G.step(dt);
  paintSky();
  /* ⚠️ ชั้นหลังลูกโลก วาดก่อนเสมอ เรียงจากไกลไปใกล้
     ดาว → เนื้อกระดาษ (พื้นผิว) → ฝุ่น → ฝน/หิมะ → ฟ้าคะนอง → เงา → ลูกโลกทับทั้งหมด
     ⛔ ฝนอยู่ *หลัง* ลูกโลก แม้ตามความจริงมันตกอยู่ระหว่างเรากับลูกโลก
        เพราะกฎของหน้านี้คือลูกโลกต้องเด่นที่สุด — ฝนบังหน้าจะแย่งไป */
  dt=REDUCED?0:dt;
  stars(sctx,dt);         /* ⛔ ก่อน grain — ดาวอยู่ไกลกว่าทุกอย่างในฉาก (ข้อ 176) */
  grain(sctx);
  dust(sctx,dt);
  syncDecks();
  rain(sctx,dt);
  snow(sctx,dt);          /* หลังฝน เพราะสองอย่างนี้ไม่อยู่พร้อมกันอยู่แล้ว (ข้อ 175) */
  splash(sctx,dt);
  bolt(sctx,dt);          /* ⛔ ต้องอยู่ *ก่อน* ลูกโลก ไม่งั้นฟ้าสว่างฉาบทับลูกโลกทั้งใบ */
  globeShade(sctx);
  const list=store.letters();
  /* นาฬิกาแสงต้องเดินตามเวลาที่กำลังดูอยู่ ไม่ใช่เวลาจริง ตอนอยู่ในโหมดจำลอง */
  if(PREVIEW){
    const P=list.find(x=>x.id===PREVIEW.id);
    SUN_MS = P ? P.s+PREVIEW.h*3600000 : null;
    if(!P) previewOff();
  }
  const all=[], flying=[];
  list.forEach(L=>{
    const st=letterState(L,nowFor(L));
    const rec={L,st,A:llOf(L.f),B:llOf(L.t)};
    all.push(rec);
    if(!st.arrived&&!st.gone) flying.push(rec);
  });
  const sel = selected ? all.find(x=>x.L.id===selected) : null;

  /* ---------- ชั้นที่หมอกบังได้: โลก + อากาศบนผิวโลก ---------- */
  G.sphere(sctx);
  /* พายุไม่ถูกวาดตรงนี้อีกแล้ว (ข้อ 62.7) — มันเป็นกระแสวนในสนามลม
     จึงถูกวาดพร้อมริ้วลมใน G.streams ซึ่งอยู่ *เหนือ* หมอก
     ตรงนี้เคยอ้างข้อ 5 ว่าอากาศเห็นได้ "ในวง" แต่ข้อ 33 เขียนไว้ตรงข้ามว่า
     พายุมองเห็นทะลุหมอกทั้งเส้นทาง และข้อ 31 บอกว่าลมทะลุหมอกเสมอ — พายุก็คือลม
     ผลที่วัดได้ตอนอยู่ใต้หมอก: พายุจางกว่าริ้วลมที่อยู่รอบตัวมันเอง สู้ไม่ได้เลย
     wxStorm() ยังอยู่ เพราะการ์ดพยากรณ์ยังใช้ผ่าน drawWx() */

  /* ---------- หมอก (ข้อ 6 · วงเดียว เฉพาะฉบับที่เลือก · ข้อ 8 · วิ่งตามจดหมาย) ---------- */
  let hole=null;
  /* ตอนย้อนดู ฉบับที่ถึงแล้วต้องมีวงเปิดเหมือนกำลังบินจริง — st มาจากเวลาที่กำลังดูอยู่แล้ว */
  if(sel && !sel.st.arrived && !sel.st.gone){
    const p=G.pipeV(posVAt(sel.L,sel.st.prog));
    const lg=sel.L.lg&&sel.L.lg[sel.st.legIdx];
    if(p.z>=-0.05) hole={x:p.x, y:p.y, r:G.R*Math.sin(revealKm(sel.L, lg?lg[6]:0)/ER)};
  }
  G.fog(sctx,hole);
  G.restoreNight(sctx,hole);
  /* ข้อ 31 — ลมทะลุหมอกเสมอ จึงต้องวาดหลังลบความทึบ
     เฉพาะฉบับที่เลือก ไม่งั้นหลายเส้นทางจะทับกันจนอ่านไม่ออกว่าลมไปทางไหน */
  if(sel && !sel.st.arrived && !sel.st.gone){
    /* ---------- เมฆ → ลม (ข้อ 70) ----------
       ขีดฝนถูกตัดทิ้ง — กอล์ฟ 25 ส.ค.: "หมอกที่เราทำตลอด ให้แทนเมฆไปเลยดีกว่าไหม
       ไม่ต้องมีฝนสักเส้น"

       ถูก และเหตุผลหนักกว่าเรื่องความสวย: **ขีดฝนเป็นสัญลักษณ์ที่ต้องเรียนรู้**
       คนต้องรู้ก่อนว่าขีดเอียงแปลว่าฝน แต่ม่านทึบไม่ต้องเรียน ใครก็รู้ว่าฟ้าครึ้มแปลว่าอะไร
       คำตอบที่ถูกจึงคือเลิกใช้สัญลักษณ์ ไม่ใช่เพิ่มคำอธิบาย

       เมฆเป็นม่านของตัวเอง วาดทับ *หลัง* หมอก จึงไม่ถูกวงเปิดเจาะ
       ถ้าใช้หมอกตัวเดียวกัน วงเปิดจะเปิดฟ้าโปร่งรอบจดหมายเสมอ
       ทั้งที่จดหมายกำลังอยู่กลางฝน — กลับหัวกับความจริง (ข้อ 6 ปะทะข้อ 70) */
    const rm=rainMarks(sel.L, sel.st.prog);
    /* ลำดับคือความหมาย: หมอกลบสิ่งที่อยู่ใต้มัน · ของที่ร่วงอยู่บนเมฆ ·
       ฟ้าแลบส่องจากในเมฆ · แต่ไม่มีอะไรได้รับอนุญาตให้กลบลม (ข้อ 84.6ง) */
    G.hatchClouds(sctx, rm, 1);
    G.fogWx(sctx, rm, 1);
    G.fall(sctx, rm, 1);
    G.snowFall(sctx, rm, 1);
    G.iceFall(sctx, rm, 1);
    G.bolts(sctx, sel.L, sel.st);
    G.streams(sctx, driftStreams(sel.L, sel.st.prog), 1);
  }

  HITS.length=0;
  /* ---------- ชั้นจดหมาย: อยู่เหนือหมอกเสมอ ----------
     หมอกปิดโลก ไม่ได้ปิดจดหมาย · ข้อ 7 หน้าเริ่มต้น = หมอก + จุดทอง + จุดปลายทาง */
  all.forEach(({L,st,A,B})=>{
    /* ⚠️ ชดเชยหมอกที่ลดลง (ข้อ 139) — พื้นชัดขึ้นแล้วรอยเด่นน้อยลง 12%
       วัดด้วยการเทียบภาพก่อน/หลังวาดรอย: .48 เคยได้ 119.8 ที่หมอก .72
       พอหมอกเป็น .48 เหลือ 105.6 · ต้องใช้ .58 ถึงจะกลับมา 120.6
       ⓘ ฉบับที่เลือกคง .92 — มันเด่นด้วยความต่างจากฉบับอื่น ไม่ใช่ด้วยค่าสัมบูรณ์ */
    const alpha = (st.arrived||st.gone) ? .32 : (selected===L.id ? .92 : .58);
    /* ข้อ 3 — ถึงแล้วรอยหายไป เหลือแค่จุดปลายทาง */
    if(!st.arrived){
      const tr=trailUpto(L,st.prog);
      if(tr) G.poly(sctx,tr,alpha);
      G.node(sctx,G.pipe(A.lat,A.lng),false);
    }
    G.node(sctx,G.pipe(B.lat,B.lng),true);
    if(st.gone) G.ghost(sctx,G.pipeV(posVAt(L,st.prog)));
  });
  flying.slice(0,CFG.MAX_ANIM).forEach(({L,st})=>{
    const p=G.pipeV(posVAt(L,st.prog));
    const pulse=1;
    /* ---------- จดหมายที่ไปต่อไม่ได้ (ข้อ 96) ----------
       ของเดิมกะพริบอยู่กับที่ แล้วเขียนว่า "จอดรอให้พายุสงบ"
       กระดาษไม่มีสมอ ไม่มีที่กำบัง ไม่มีเจตจำนง — **มันจอดไม่ได้**
       และการกะพริบเป็นภาษาของ UI (แจ้งเตือน) ไม่ใช่ภาษาของลม

       กอล์ฟ: "เวลาเราบอกวน คือวน เวลาบอกติดอยู่ในพายุ คือติดจริง ๆ"
       คำจึงต้องแยกตามชนิด เพราะการเคลื่อนไหวสองแบบนี้ต่างกันจริง (ข้อ 93)

       ลมกระโชก (sev 1-2) — **ไม่มีศูนย์กลางให้วนรอบ** ถ้าวาดให้วนก็โกหกอีกแบบ
         → ปั่นไปมาด้วยคลื่นสามความถี่ที่ไม่ลงตัวกัน ไม่มีจังหวะซ้ำ เดาไม่ได้
       พายุหมุน (sev 3) — มีตาจริง
         → ก้นหอยที่รัศมีหด-ขยาย อ่านเป็นการถูกดูดเข้าแล้วเหวี่ยงออก วนไม่หลุด

       ⚠️ เป็นระยะ *บนจอ* ไม่ใช่ระยะภูมิศาสตร์ — นี่คือการสั่นเชิงภาพ ไม่ใช่การย้ายที่
       ตำแหน่งจริงไม่ขยับเลย เส้นทางและเวลารวมจึงไม่เปลี่ยนแม้แต่นิดเดียว */
    if(st.parked){
      const t=T*(0.75+clamp((st.sev||1)/3,0,1)*0.5);
      if((st.sev||0)>=3){
        const a=t*1.15;
        const r=CFG.HOLD_PX*(0.40+0.60*(0.5+0.5*Math.sin(T*0.45)));
        p.x+=Math.cos(a)*r; p.y+=Math.sin(a)*r;
      }else{
        const r=CFG.HOLD_PX*0.82;
        p.x+=(Math.sin(t*1.7)+Math.sin(t*2.9+1.3)*0.7+Math.sin(t*4.7+2.1)*0.4)/2.1*r;
        p.y+=(Math.cos(t*1.3+0.8)+Math.cos(t*3.3+2.6)*0.7+Math.cos(t*5.1)*0.4)/2.1*r;
      }
    }
    /* ข้อ 24-25 — ซูมเข้าพอ จุดทองค่อย ๆ กลายเป็นแผ่นกระดาษจริง
       เกณฑ์ผูกกับ "วงเปิดกว้างกี่พิกเซล" ไม่ใช่ระดับซูมตรง ๆ เพราะซูมที่พอดี
       ของเส้นในจังหวัดกับของเส้นข้ามทวีปห่างกัน 17 เท่า */
    /* ข้อ 25 บอกว่าจุดทองกลายเป็นกระดาษราว "2-3 เท่า" — ต้องอ่านว่า
       2-3 เท่าของ*ภาพตั้งต้นของฉบับนั้น* ไม่ใช่ 2-3 เท่าสัมบูรณ์
       ไม่งั้นเส้นในจังหวัดจะไม่มีวันเห็นกระดาษ เพราะซูมพอดีของมันอยู่ที่ 16 เท่าแล้ว */
    const fitz = selected===L.id ? G.fitZoom(fitKm(L)) : 0;
    const paper = fitz ? clamp(G.zoom/fitz-1.3, 0, 1) : 0;
    if(p.z>=0) HITS.push({id:L.id,x:p.x,y:p.y});
    if(paper<1) G.dot(sctx,p,pulse*(1-paper), selected===L.id);
    if(paper>0 && p.z>=0){
      const wnd=(L.lg&&L.lg[st.legIdx]) ? clamp(L.lg[st.legIdx][2]/90,.1,1) : .3;
      const ps=26+40*paper;
      sctx.save(); sctx.globalAlpha=paper;
      drawFlutter(sctx,p.x,p.y,ps*.72,ps,T,wnd,0,null);
      sctx.restore();
    }
  });
  flying.slice(CFG.MAX_ANIM).forEach(({L,st})=>{
    const q=G.pipeV(posVAt(L,st.prog));
    if(q.z>=0) HITS.push({id:L.id,x:q.x,y:q.y});
    G.dot(sctx,q,1,selected===L.id);
  });
}

